#!/usr/bin/env python3
"""
Wires up alternate app icons for the CI build.

Convention: each subfolder of icons/ at the repo root is one selectable icon, named after the
folder (e.g. icons/Infinitok_Dark/ -> an icon named "Infinitok_Dark" in the picker). Each folder
must contain:
    AppIcon60x60@2x.png   (120x120, required — iPhone)
    AppIcon60x60@3x.png   (180x180, required — iPhone)

iPad needs its own size class (76x76pt and 83.5x83.5pt, not 60x60pt) — declaring the iPhone-sized
files under CFBundleIcons~ipad too is invalid, and simply not declaring that key at all makes the
icon disappear from the picker entirely on iPad, because iOS transparently substitutes
CFBundleIcons~ipad for CFBundleIcons when an app queries the generic key while running on iPad —
so if that key never had this icon, the substituted lookup finds nothing. Real iPad-specific
artwork isn't required here: the required iPad sizes (152x152, 167x167) are generated by
upscaling the @3x (180x180) source with Pillow, which is more than adequate for a solid-color
Home Screen icon like this one and satisfies iOS's completeness check either way.

For every icon folder, this script:
  1. Copies both provided iPhone PNGs into the app bundle root with a flattened, collision-safe
     filename (<FolderName>_AppIcon60x60@2x.png / @3x.png).
  2. Generates and copies the two required iPad sizes the same way
     (<FolderName>_AppIcon76x76@2x.png, <FolderName>_AppIcon83.5x83.5@2x.png).
  3. Adds a CFBundleAlternateIcons entry under both CFBundleIcons and CFBundleIcons~ipad in
     Info.plist, each pointing at its own correctly-sized files.

Runtime code (Settings/AppIconViewController.m) reads these same Info.plist keys dynamically —
neither side hardcodes icon names, so dropping a new folder in icons/ and re-running the build is
the entire process for adding a new selectable icon. No code changes needed on either side.

Usage: apply_alternate_icons.py <path-to-app-bundle> <path-to-icons-folder>
"""
import plistlib
import shutil
import sys
from pathlib import Path

from PIL import Image

REQUIRED_IPHONE_FILES = ["AppIcon60x60@2x.png", "AppIcon60x60@3x.png"]
# (source_file_to_scale_from, output_filename, output_pixel_size)
IPAD_SIZES = [
    ("AppIcon60x60@3x.png", "AppIcon76x76@2x.png", 152),
    ("AppIcon60x60@3x.png", "AppIcon83.5x83.5@2x.png", 167),
]


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <path-to-app-bundle> <path-to-icons-folder>", file=sys.stderr)
        sys.exit(1)

    app_dir = Path(sys.argv[1])
    icons_dir = Path(sys.argv[2])
    info_plist_path = app_dir / "Info.plist"

    if not app_dir.is_dir():
        print(f"::error::App bundle not found at {app_dir}", file=sys.stderr)
        sys.exit(1)
    if not info_plist_path.is_file():
        print(f"::error::Info.plist not found at {info_plist_path}", file=sys.stderr)
        sys.exit(1)
    if not icons_dir.is_dir():
        print(f"No icons/ folder at {icons_dir} — skipping alternate icon setup.")
        return

    icon_folders = sorted(p for p in icons_dir.iterdir() if p.is_dir())
    if not icon_folders:
        print("icons/ folder exists but has no subfolders — nothing to add.")
        return

    with open(info_plist_path, "rb") as f:
        info = plistlib.load(f)

    iphone_alternates = {}
    ipad_alternates = {}
    added = []
    skipped = []

    for folder in icon_folders:
        name = folder.name
        missing = [f for f in REQUIRED_IPHONE_FILES if not (folder / f).is_file()]
        if missing:
            skipped.append((name, f"missing {', '.join(missing)}"))
            continue

        for f in REQUIRED_IPHONE_FILES:
            src = folder / f
            dest_path = app_dir / f"{name}_{f}"
            # Re-encode through Pillow rather than a raw copy. Icon source files in this repo
            # have been found saved as JPEG data with a misleading .png extension (shutil.copy2
            # preserves bytes verbatim, so a mislabeled source produces a mislabeled file in the
            # bundle too) — iOS's icon-specific decoder can reject or silently fail to render that,
            # unlike the IPAD_SIZES path below, which already re-encodes via Pillow's save() and so
            # was unaffected. Opening and re-saving here guarantees genuine PNG bytes regardless of
            # what format the source file actually is.
            with Image.open(src) as img:
                img.convert("RGB").save(dest_path, format="PNG")
            dest_path.chmod(0o644)

        for source_file, output_file, pixel_size in IPAD_SIZES:
            with Image.open(folder / source_file) as img:
                resized = img.convert("RGB").resize((pixel_size, pixel_size), Image.LANCZOS)
                dest_path = app_dir / f"{name}_{output_file}"
                resized.save(dest_path)
                dest_path.chmod(0o644)

        # CFBundleIconFiles entries are base names without the @2x/@3x/.png suffix — iOS resolves
        # the actual scale variant itself from whichever of those flattened files are present.
        iphone_alternates[name] = {
            "CFBundleIconFiles": [f"{name}_AppIcon60x60"],
            "UIPrerenderedIcon": False,
        }
        ipad_alternates[name] = {
            "CFBundleIconFiles": [f"{name}_AppIcon76x76", f"{name}_AppIcon83.5x83.5"],
            "UIPrerenderedIcon": False,
        }
        added.append(name)

    if not added:
        print("No valid icon folders found (each needs AppIcon60x60@2x.png and @3x.png).")
        for name, reason in skipped:
            print(f"  skipped {name}: {reason}")
        return

    for key, alternates in (("CFBundleIcons", iphone_alternates), ("CFBundleIcons~ipad", ipad_alternates)):
        existing = info.get(key) or {}
        existing_alternates = existing.get("CFBundleAlternateIcons") or {}
        existing_alternates.update(alternates)
        existing["CFBundleAlternateIcons"] = existing_alternates
        info[key] = existing

    with open(info_plist_path, "wb") as f:
        plistlib.dump(info, f)

    print(f"Added {len(added)} alternate icon(s): {', '.join(added)}")
    for name, reason in skipped:
        print(f"  skipped {name}: {reason}")


if __name__ == "__main__":
    main()
